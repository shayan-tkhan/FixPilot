import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.BASE_URL || 'http://localhost:3000';
const b=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const errors=[];
async function signIn(role){const context=await b.newContext({viewport:{width:390,height:844}});const p=await context.newPage();p.on('pageerror',e=>errors.push(e.message));await p.goto(base);await p.getByRole('button',{name:role,exact:true}).click();await p.getByLabel('Password',{exact:true}).fill('demo123');await p.getByRole('button',{name:'Open workspace'}).click();await p.waitForURL('**/operations');return p;}
const student=await signIn('Student / User');
await student.getByRole('button',{name:'Report New Issue',exact:true}).first().click();
await student.getByRole('combobox',{name:'Category',exact:true}).selectOption('Water');
await student.getByLabel('Issue title',{exact:true}).fill('Leaking tap in hostel');
await student.getByLabel('Description',{exact:true}).fill('The bathroom tap is leaking continuously.');
const location='Hostel flow '+Date.now();
await student.getByLabel('Location',{exact:true}).fill(location);
await student.getByRole('button',{name:'Submit issue'}).click();await student.getByRole('dialog').waitFor({state:'hidden'});
await student.getByText('Your department is reviewing the issue and will assign a technician.').waitFor();
const staff=await signIn('Department Staff');
await staff.getByRole('button',{name:'Assign technician',exact:true}).click();
await staff.getByRole('button').filter({has:staff.getByRole('heading',{name:'Leaking tap in hostel',exact:true})}).filter({hasText:location}).click();
await staff.getByRole('combobox',{name:'Department',exact:true}).selectOption('Maintenance');
await staff.getByRole('combobox',{name:'Technician',exact:true}).selectOption('operator@fixpilot.demo');
await staff.getByLabel('Estimated minutes').fill('15');
await staff.getByRole('button',{name:'Save assignment'}).click();
await staff.getByText('Assigned to Alex Morgan · Maintenance.').waitFor();
const tech=await signIn('Technician');
await tech.getByRole('button',{name:'Start a task',exact:true}).click();
await tech.getByRole('button').filter({has:tech.getByRole('heading',{name:'Leaking tap in hostel',exact:true})}).filter({hasText:location}).click();
await tech.getByRole('button',{name:'Start work',exact:true}).click();
await tech.getByText('Alex Morgan started work.').waitFor();
await tech.locator('label').filter({hasText:'After photo'}).locator('input').setInputFiles({name:'repair-proof.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==','base64')});
await tech.getByRole('link',{name:'After repair · repair-proof.png'}).waitFor();
await tech.getByLabel('Repair note').fill('Replaced the seal and checked the tap.');
await tech.getByRole('button',{name:'Submit completion',exact:true}).click();
await tech.getByText('Completion sent. Department staff will review your repair.').waitFor();
await tech.screenshot({path:'work/basic-technician.png',fullPage:true});
await staff.getByRole('button',{name:'Approve repair',exact:true}).waitFor({timeout:15000});
await staff.screenshot({path:'work/basic-staff.png',fullPage:true});
await staff.getByRole('button',{name:'Approve repair',exact:true}).click();
await student.getByRole('button',{name:'Problem solved',exact:true}).waitFor({timeout:15000});
await student.getByRole('button',{name:'Problem solved',exact:true}).click();
await student.getByText('You confirmed this issue is solved.').waitFor();
await student.screenshot({path:'work/basic-student.png',fullPage:true});
await student.getByRole('button',{name:'Reopen issue',exact:true}).click();
